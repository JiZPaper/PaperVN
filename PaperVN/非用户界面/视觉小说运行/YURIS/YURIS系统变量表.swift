import Foundation

/// 不同版本的系统变量编号不一样。这里把脚本里的编号统一换算成虚拟机用的编号（0.472～0.479 的布局）。
/// 由官方编译器各版本的 YSCom.ycd 整理：系统变量的总数就能确定布局。
/// 每个区间是（文件里的起点，虚拟机里的起点，个数）。这个版本没有对应项的放到 530 以后。
nonisolated enum YURIS系统变量表 {
    private static let 布局: [Int: [(Int, Int, Int)]] = [
        496: [(0, 0, 32), (32, 48, 23), (55, 81, 6), (61, 91, 435)], // 450～451
        513: [(0, 0, 71), (71, 81, 6), (77, 90, 436)], // 452～466
        516: [(0, 0, 71), (71, 81, 445)], // 470～471
        538: [(0, 0, 71), (71, 530, 6), (77, 71, 10), (87, 536, 6), (93, 81, 445)], // 480～480
        541: [(0, 0, 50), (50, 530, 3), (53, 50, 21), (74, 533, 6), (80, 71, 10), (90, 539, 6), (96, 81, 445)], // 484～493
        548: [(0, 0, 50), (50, 530, 3), (53, 50, 4), (57, 533, 3), (60, 54, 4), (64, 536, 3), (67, 58, 3), (70, 539, 1), (71, 61, 10), (81, 540, 6), (87, 71, 10), (97, 546, 6), (103, 81, 445)], // 494～494
    ]

    /// 总数对不上时（0.450 以前没有资料）返回 nil，按虚拟机自己的编号理解
    static func 映射(系统变量数 count: Int) -> [Int]? {
        guard let ranges = 布局[count] else { return nil }
        var map = Array(0..<max(count, 1000))
        for (physical, logical, length) in ranges {
            for offset in 0..<length where physical + offset < map.count { map[physical + offset] = logical + offset }
        }
        return map
    }
}
